// ============================================================================
// 객체지향 프로그래밍(OOP)의 출발점
// ============================================================================
//
// → 객체지향 프로그래밍은 데이터를 외부에서 직접 변경하지 못하게 하고,
//   메소드를 통해 데이터를 다루는 방식으로 유지보수를 편리하게 만들 수 있다.
//
// ■ 접근 제한자
// public  : 모든 클래스에서 접근 가능
// private : 현재 클래스에서만 접근 가능
//
// private 멤버변수는 외부에서 직접 접근할 수 없기 때문에
// public 메소드를 통해 값을 설정하거나 가져온다.
//
// → 값을 설정하는 메소드 : Setter
// → 값을 가져오는 메소드 : Getter
// ============================================================================


class Person {

    // ------------------------------------------------------------------------
    // 멤버변수
    // ------------------------------------------------------------------------
    //
    // private
    // → Person 클래스 외부에서는 직접 접근할 수 없음
    // ------------------------------------------------------------------------

    private String name;
    private int age;


    // ------------------------------------------------------------------------
    // Setter
    // ------------------------------------------------------------------------
    //
    // 외부에서 private 변수 name에 값을 저장하기 위한 메소드
    // ------------------------------------------------------------------------

    public void setName(String n) {

        name = n + "님";
    }


    // ------------------------------------------------------------------------
    // Getter
    // ------------------------------------------------------------------------
    //
    // 외부에서 private 변수 name의 값을 가져오기 위한 메소드
    // ------------------------------------------------------------------------

    public String getName() {

        return name;
    }


    // ------------------------------------------------------------------------
    // Setter
    // ------------------------------------------------------------------------
    //
    // 외부에서 private 변수 age에 값을 저장하기 위한 메소드
    // ------------------------------------------------------------------------

    public void setAge(int a) {

        age = a;
    }


    // ------------------------------------------------------------------------
    // Getter
    // ------------------------------------------------------------------------
    //
    // 외부에서 private 변수 age의 값을 가져오기 위한 메소드
    // ------------------------------------------------------------------------

    public int getAge() {

        return age;
    }
}


// ============================================================================
// 실행 클래스
// ============================================================================

public class OOPEx1 {

    public static void main(String[] args) {


        // --------------------------------------------------------------------
        // 객체 생성
        // --------------------------------------------------------------------

        Person p1 = new Person();


        // --------------------------------------------------------------------
        // private 멤버변수에 직접 접근할 수 없음
        // --------------------------------------------------------------------
        //
        // p1.name = "김길동"; // private이므로 직접 접근 불가
        // p1.age = 20;       // private이므로 직접 접근 불가
        //
        // → public 메소드를 통해 값을 설정한다.
        // --------------------------------------------------------------------

        p1.setName("김길동");
        p1.setAge(20);


        // --------------------------------------------------------------------
        // Getter를 사용하여 값 가져오기
        // --------------------------------------------------------------------

        System.out.println(p1.getName());
        System.out.println(p1.getAge());


        // ====================================================================
        // 두 번째 객체
        // ====================================================================

        Person p2 = new Person();

        p2.setName("박길동");
        p2.setAge(25);


        // ====================================================================
        // 세 번째 객체
        // ====================================================================

        Person p3 = new Person();

        p3.setName("홍길동");
        p3.setAge(30);
    }
}