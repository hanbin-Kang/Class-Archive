// ============================================================================
// 멤버변수와 지역변수 구분
// ============================================================================
//
// ■ 멤버변수
// - 클래스 내부에 선언된 변수
// - 객체가 생성되면 사용할 수 있음
// - 초기화 값을 지정하지 않아도 자동으로 기본값으로 초기화됨
//
// ■ 지역변수
// - 메소드, 반복문 등의 특정 영역 안에서 선언된 변수
// - 선언된 영역 안에서만 사용 가능
// - 자동 초기화되지 않으므로 반드시 직접 초기화해야 함
//
// ★ 핵심
// → 변수 선언 위치로 멤버변수와 지역변수를 구분한다.
// ============================================================================


class MyMember {

    int y;              // 멤버변수 → 객체 생성 시 기본값 0으로 자동 초기화
    static int j = 50;  // static 멤버변수 → 클래스에 소속
}

public class MemberVariableEx {

    int k = 30; // 멤버변수 → 객체가 생성되어야 사용할 수 있음


    // =========================================================================
    // main 메소드
    // =========================================================================
    //
    // 프로그램이 실행되면 JVM이 main 메소드를 찾아 실행한다.
    // static이므로 객체를 생성하지 않아도 호출할 수 있다.
    //
    // main 메소드 내부에서 선언한 변수는 지역변수이다.
    // =========================================================================

    public static void main(String[] args) {

        // ---------------------------------------------------------------------
        // 1. 지역변수
        // ---------------------------------------------------------------------
        //
        // main 메소드 내부에서 선언했으므로 지역변수
        // → main 메소드 안에서만 사용 가능
        //
        // 지역변수는 자동 초기화되지 않기 때문에 값을 직접 넣어야 한다.
        // ---------------------------------------------------------------------

        int x = 10;

        System.out.println(x);


        // ---------------------------------------------------------------------
        // 2. MyMember의 멤버변수 y
        // ---------------------------------------------------------------------
        //
        // y는 MyMember 클래스의 멤버변수
        //
        // new MyMember()
        // → MyMember 객체 생성
        // → 객체의 참조값을 m에 저장
        //
        // m.y
        // → m이 참조하는 객체의 y에 접근
        //
        // y에 값을 넣지 않았으므로 기본값 0이 출력된다.
        // ---------------------------------------------------------------------

        MyMember m = new MyMember();

        System.out.println(m.y);


        // ---------------------------------------------------------------------
        // 3. MemberVariableEx의 멤버변수 k
        // ---------------------------------------------------------------------
        //
        // k는 MemberVariableEx 클래스의 멤버변수
        //
        // main은 static이므로 MemberVariableEx 객체가 아니다.
        // 따라서 k를 사용하려면 객체를 먼저 생성해야 한다.
        // ---------------------------------------------------------------------

        MemberVariableEx z = new MemberVariableEx();

        System.out.println(z.k);


        // ---------------------------------------------------------------------
        // 4. static 멤버변수 j
        // ---------------------------------------------------------------------
        //
        // j는 static이므로 객체가 아니라 클래스에 소속된다.
        //
        // 따라서 객체를 생성하지 않아도 사용할 수 있다.
        // 클래스명.변수명 형태로 접근한다.
        // ---------------------------------------------------------------------

        System.out.println(MyMember.j);
    }
}