// ============================================================================
// 생성자(Constructor)
// ============================================================================
//
// ■ 생성자
// - 객체가 생성될 때 자동으로 호출되는 특별한 메소드
// - 주로 멤버변수를 초기화할 때 사용
//
// ■ 생성자 문법
// - 메소드와 비슷한 형태
// - 리턴형을 작성하지 않음
// - 생성자의 이름은 반드시 클래스명과 같아야 함
//
// ■ 생성자 호출
// → new 클래스명(...)을 실행하면 해당 생성자가 호출됨
//
// ■ 생성자 오버로딩
// - 매개변수의 개수나 타입이 다른 생성자를 여러 개 만들 수 있음
// - 객체를 생성할 때 전달한 인자에 맞는 생성자가 호출됨
// ============================================================================


class MyCon {

    // ------------------------------------------------------------------------
    // 멤버변수
    // ------------------------------------------------------------------------

    String name;
    int age;


    // ------------------------------------------------------------------------
    // 기본 생성자
    // ------------------------------------------------------------------------
    //
    // new MyCon()으로 객체를 생성하면 호출됨
    // ------------------------------------------------------------------------

    public MyCon() {

        age = 20;
        name = "홍길동";
    }


    // ------------------------------------------------------------------------
    // 생성자 ①
    // ------------------------------------------------------------------------
    //
    // 매개변수 : int, String
    //
    // new MyCon(10, "김우욱")으로 객체를 생성하면 호출됨
    // ------------------------------------------------------------------------

    public MyCon(int a, String n) {

        age = a;
        name = n;

        // System.out.println("생성자 호출"); // 테스트용
    }


    // ------------------------------------------------------------------------
    // 생성자 ②
    // ------------------------------------------------------------------------
    //
    // 매개변수 : String, int
    //
    // new MyCon("박길동", 50)으로 객체를 생성하면 호출됨
    // ------------------------------------------------------------------------

    public MyCon(String n, int a) {

        name = n;
        age = a;
    }
}


// ============================================================================
// 실행 클래스
// ============================================================================

public class ConstructorEx {

    public static void main(String[] args) {

        // --------------------------------------------------------------------
        // 생성자 ① 호출
        // --------------------------------------------------------------------
        //
        // int → String 순서이므로
        // MyCon(int a, String n)이 호출됨
        // --------------------------------------------------------------------

        MyCon m1 = new MyCon(10, "김우욱");

        System.out.println(m1.name);


        // --------------------------------------------------------------------
        // 생성자 ② 호출
        // --------------------------------------------------------------------
        //
        // String → int 순서이므로
        // MyCon(String n, int a)이 호출됨
        // --------------------------------------------------------------------

        MyCon m2 = new MyCon("박길동", 50);

        System.out.println(m2.name);
    }
}