class MyA extends Object {

    int x = 10;


    // ============================================================
    // 1. 기본 생성자
    // ============================================================

    public MyA() {
    }


    // ============================================================
    // 2. 매개변수를 받는 생성자
    // ============================================================

    // 생성자를 하나라도 직접 만들면
    // 컴파일러가 기본 생성자(MyA())를 자동으로 만들어주지 않음
    public MyA(int x) {

        // this.x → MyA 클래스의 멤버변수 x
        // x      → 생성자의 매개변수 x
        //
        // 전달받은 x값을 MyA의 멤버변수 x에 저장
        this.x = x;
    }


    // ============================================================
    // 3. x값을 출력하는 메소드
    // ============================================================

    public void printX() {

        // 이 메소드는 MyA에서 만들어졌기 때문에
        // 여기서 x는 MyA의 멤버변수 x를 의미함
        System.out.println("x = " + x);
    }
}


// ==================================================================
// MyA를 상속받는 MyB
// ==================================================================

class MyB extends MyA {

    // MyA의 x와는 별개의 x
    int x = 10;


    // ============================================================
    // MyB의 생성자
    // ============================================================

    public MyB(int x) {

        // 생성자는 상속되지 않음
        
        // super(x)
        // → 부모 클래스 MyA의 MyA(int x) 생성자를 호출
        
        // 따라서 MyA의 x에 전달받은 값을 저장
        super(x);
    }
}


// ==================================================================
// 실행 클래스
// ==================================================================

public class ExtendsEx {

    public static void main(String[] args) {


        // ============================================================
        // 1. MyA 객체 생성
        // ============================================================

        MyA a = new MyA(5);

        System.out.println(a.x);
        a.printX();


        // ============================================================
        // 2. MyB 객체 생성
        // ============================================================

        MyB b = new MyB(15);

        /*
         * new MyB(15)를 실행하면
         *
         * MyB 생성자 실행
         *     ↓
         * super(15)
         *     ↓
         * MyA(int x) 실행
         *     ↓
         * MyA의 x = 15
         *
         * 그리고 MyB에도 별도의 x가 존재함
         *
         * ┌─────────────────────┐
         * │      MyB 객체      
         * │                     
         * │ MyA의 x = 15        
         * │ MyB의 x = 10        
         * └─────────────────────┘
         */


        // ============================================================
        // 3. b.x 출력
        // ============================================================

        System.out.println(b.x);

        // b의 타입은 MyB이므로
        // b.x는 MyB에서 선언한 x를 의미함
        
        // MyB의 x는 처음에 10으로 초기화됨
        
        // 출력 결과
        // 10


        // ============================================================
        // 4. b.x의 값 변경
        // ============================================================

        b.x = 20;

        // b.x는 MyB의 x이므로
        // MyB의 x만 20으로 변경됨
        
        // 현재 상태
        
        // ┌─────────────────────┐
        // │      MyB 객체       
        // │                     
        // │ MyA의 x = 15         ← 그대로
        // │ MyB의 x = 20         ← 변경됨
        // └─────────────────────┘


        // ============================================================
        // 5. printX() 실행
        // ============================================================

        b.printX();

        // printX() 메소드는 MyA에서 만들어짐
        
        // MyB에는 printX()가 없기 때문에
        // MyA의 printX()를 상속받아서 사용함
        
        // 따라서 printX() 내부의 x는
        // MyA의 멤버변수 x를 의미함
        
        // MyA의 x = 15
        // MyB의 x = 20
        
        // b.x = 20으로 변경했지만
        // printX()에서 사용하는 x는 MyA의 x이므로
        // 20이 아니라 15가 출력됨
        
        // 출력 결과
        // x = 15
    }
}